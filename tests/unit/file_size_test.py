"""No module over 800 lines grows: a baseline ratchet over `src/` (the locality plan's size rule).

The baseline lists every file over the limit with its line count. A listed file may not grow; a file that is not
listed may not pass the limit; a file that shrank lowers its line, and one that fell under the limit leaves the list.
Regenerate after a split with:

    uv run python tests/unit/file_size_test.py --write
"""

import sys
import tomllib
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
BASELINE = Path(__file__).with_name("file_size_baseline.toml")
LIMIT = 800
HEADER = "# Generated by `uv run python tests/unit/file_size_test.py --write`. Listed files may not grow.\n"

pytestmark = pytest.mark.unit


def sizes(root: Path = ROOT) -> dict[str, int]:
    """Line counts of the Python files under `src/` that are over the limit, by repository path."""
    found: dict[str, int] = {}
    for path in sorted((root / "src").rglob("*.py")):
        lines = len(path.read_text(encoding="utf-8").splitlines())
        if lines > LIMIT:
            found[path.relative_to(root).as_posix()] = lines
    return found


def baseline() -> dict[str, int]:
    """The line counts the baseline allows."""
    listed: dict[str, int] = tomllib.loads(BASELINE.read_text(encoding="utf-8"))["lines"]
    return {str(path): int(lines) for path, lines in listed.items()}


def problems(now: dict[str, int], allowed: dict[str, int]) -> list[str]:
    """What breaks the ratchet: growth, a new file over the limit, a shrink or a split the baseline does not show."""
    found: list[str] = []
    for path, lines in now.items():
        if path not in allowed:
            found.append(f"{path} has {lines} lines, over {LIMIT}: split it by concern")
        elif lines > allowed[path]:
            found.append(f"{path} grew from {allowed[path]} to {lines} lines: split it, never grow it")
        elif lines < allowed[path]:
            found.append(f"{path} shrank to {lines} lines: lower its baseline (--write)")
    gone = [path for path in allowed if path not in now]
    found += [f"{path} is under {LIMIT} lines now: drop it from the baseline (--write)" for path in gone]
    return found


def test_no_large_module_grows() -> None:
    assert problems(sizes(), baseline()) == []


def test_the_ratchet_refuses_growth_new_large_files_and_a_stale_baseline() -> None:
    found = problems({"src/a.py": 901, "src/new.py": 801}, {"src/a.py": 900, "src/gone.py": 850})
    assert [line.split(" ")[0] for line in found] == ["src/a.py", "src/new.py", "src/gone.py"]
    shrunk = problems({"src/a.py": 899}, {"src/a.py": 900})
    assert shrunk == ["src/a.py shrank to 899 lines: lower its baseline (--write)"]
    assert problems({"src/a.py": 900}, {"src/a.py": 900}) == []


def test_the_inventory_rejects_an_oversized_file(tmp_path: Path) -> None:
    source = tmp_path / "src"
    source.mkdir()
    (source / "at_limit.py").write_text("# line\n" * LIMIT)
    too_large = source / "too_large.py"
    too_large.write_text("# line\n" * (LIMIT + 1))

    assert problems(sizes(tmp_path), {}) == [
        f"src/too_large.py has {LIMIT + 1} lines, over {LIMIT}: split it by concern"
    ]


def write() -> None:
    """Write the baseline from the tree as it is."""
    body = "".join(f'"{path}" = {lines}\n' for path, lines in sizes().items())
    BASELINE.write_text(f"{HEADER}[lines]\n{body}", encoding="utf-8")


if __name__ == "__main__" and sys.argv[1:] == ["--write"]:
    write()
