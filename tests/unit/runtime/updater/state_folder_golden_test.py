"""The refactored update code reads a state folder hz 0.9.53 wrote and writes the same bytes (a real tree, checked in).

`tests/fixtures/state_folder_0_9_53/` was generated by the published 0.9.53 wheel (see its README), not by this code.
"""

import hashlib
import shutil
from pathlib import Path

import pytest

from heinzel.modules.system.updater._adapter_state import FileInstallationState
from heinzel.modules.system.updater._announced import ToolSnapshot

pytestmark = pytest.mark.unit

GOLDEN = Path(__file__).resolve().parents[3] / "fixtures/state_folder_0_9_53"


def tree(root: Path) -> dict[str, bytes | str]:
    """Every file by relative path: its bytes, or its target for a symlink (modification times are not state)."""
    found: dict[str, bytes | str] = {}
    for path in sorted(root.rglob("*")):
        name = path.relative_to(root).as_posix()
        if path.is_symlink():
            found[name] = f"-> {path.readlink()}"
        elif path.is_file():
            found[name] = path.read_bytes()
        else:
            found[name + "/"] = b""
    return found


def test_the_state_folder_the_new_code_writes_is_byte_identical_to_the_one_0_9_53_wrote(tmp_path):
    prefix = tmp_path / "tool"
    shutil.copytree(GOLDEN / "after_take_prefix", prefix, symlinks=True)
    state = FileInstallationState(tmp_path / "state")
    ToolSnapshot.take(prefix, state.folder)
    assert tree(state.folder) == tree(GOLDEN / "after_take")


def test_a_put_back_that_0_9_53_left_half_way_is_finished_by_the_new_code(tmp_path):
    prefix = tmp_path / "tool"
    prefix.mkdir()  # 0.9.53 had moved every entry aside when it stopped
    state = tmp_path / "state"
    shutil.copytree(GOLDEN / "interrupted", state, symlinks=True)
    snapshot = ToolSnapshot(prefix, state / "before-update", state / "after-update")
    snapshot.recover()
    assert tree(prefix) == tree(GOLDEN / "after_take_prefix")
    assert not snapshot.copy.exists()
    assert not snapshot.aside.exists()


def test_a_next_update_over_a_folder_0_9_53_left_recovers_first_and_writes_the_same_copy(tmp_path):
    prefix = tmp_path / "tool"
    prefix.mkdir()
    state = FileInstallationState(tmp_path / "state")
    shutil.copytree(GOLDEN / "interrupted", state.folder, symlinks=True, dirs_exist_ok=True)
    ToolSnapshot.take(prefix, state.folder)
    assert tree(prefix) == tree(GOLDEN / "after_take_prefix")
    assert tree(state.folder) == tree(GOLDEN / "after_take")


BLOBS = {
    "after_take/before-update": "5888686f7959a08d35b829bc0f2d4841132cdd2d",
    "after_take_prefix": "5888686f7959a08d35b829bc0f2d4841132cdd2d",
    "interrupted/before-update": "5888686f7959a08d35b829bc0f2d4841132cdd2d",
    "interrupted/after-update": "78ca9ee3e03b2cd744eae0bb333894c6a37b37b9",
}
"""Git blob ids of the `lib/site/heinzel.py` files 0.9.53 wrote: `version = '0.9.53'` in single quotes, as its wheel's
writer produced them (a formatter that rewrote the quotes would change the bytes and fail here)."""


def blob_id(path: Path) -> str:
    data = path.read_bytes()
    return hashlib.sha1(b"blob %d\0" % len(data) + data, usedforsecurity=False).hexdigest()


def test_the_golden_tree_is_complete_in_git_and_byte_exact():
    """`lib/` and `site/` look ignorable to a gitignore and a formatter likes double quotes; neither may touch it."""
    for name, expected in BLOBS.items():
        path = GOLDEN / name / "lib/site/heinzel.py"
        assert path.is_file(), name
        assert blob_id(path) == expected, f"{name}: the bytes are not the ones 0.9.53 wrote"
