"""Git's exact push-ref input survives the hook runner, including every ref of a multi-ref push."""

import importlib.util
import os
import subprocess
from pathlib import Path

import pytest

pytestmark = pytest.mark.unit

REPO = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("install_push_hook", REPO / "scripts" / "install_push_hook.py")
assert spec
assert spec.loader
hooks = importlib.util.module_from_spec(spec)
spec.loader.exec_module(hooks)


@pytest.mark.parametrize("exit_code", [0, 7])
@pytest.mark.parametrize(
    "refs",
    [
        b"",
        b"\n",
        f"refs/heads/first {'1' * 40} refs/heads/first {'0' * 40}".encode(),
        f"refs/heads/first {'1' * 40} refs/heads/first {'0' * 40}\n\n".encode(),
        f"(delete) {'0' * 40} refs/heads/old {'1' * 40}\n".encode(),
        f"refs/heads/same {'1' * 40} refs/heads/same {'1' * 40}\n".encode(),
        (
            f"refs/heads/first {'1' * 40} refs/heads/first {'0' * 40}\n"
            f"refs/heads/second {'2' * 40} refs/heads/second {'0' * 40}\n"
        ).encode(),
    ],
    ids=["empty", "newline", "no-final-newline", "trailing-newlines", "deletion", "no-op", "multi-ref"],
)
def test_the_wrapper_preserves_every_ref_and_replays_input_to_prek(tmp_path, exit_code, refs):
    runner = tmp_path / "prek"
    observed = tmp_path / "observed"
    scanner = tmp_path / "uv"
    scanner.write_text(
        '#!/bin/sh\ncat > "$OBSERVED.scan"\nprintf \'%s\\n\' "$PRE_COMMIT_REMOTE_URL" > "$OBSERVED.remote"\n'
    )
    scanner.chmod(0o755)
    runner.write_text(
        '#!/bin/sh\nprintf \'%s\\n\' "$HZ_DEV_PUSH_REFS_FILE" > "$OBSERVED.path"\n'
        'cat "$HZ_DEV_PUSH_REFS_FILE" > "$OBSERVED.saved"\ncat > "$OBSERVED.stdin"\n'
        f"exit {exit_code}\n"
    )
    runner.chmod(0o755)
    hook = tmp_path / "pre-push"
    hook.write_text(
        f'#!/bin/sh\n# File generated by prek: https://prek.j178.dev\nPREK="{runner}"\n'
        'exec "$PREK" hook-impl --hook-type=pre-push -- "$@"\n'
    )
    hook.chmod(0o755)
    hooks.preserve_refs(hook)
    once = hook.read_bytes()
    hooks.preserve_refs(hook)
    assert hook.read_bytes() == once
    done = subprocess.run(
        [str(hook), "origin", "unused"],
        input=refs,
        env=os.environ
        | {
            "OBSERVED": str(observed),
            "HZ_DEV_PUSH_REFS_FILE": "stale inherited input",
            "TMPDIR": str(tmp_path),
            "PATH": f"{tmp_path}{os.pathsep}{os.environ['PATH']}",
        },
        capture_output=True,
        check=False,
        timeout=5,
    )
    assert done.returncode == exit_code, done.stderr
    assert observed.with_suffix(".saved").read_bytes() == refs
    assert observed.with_suffix(".stdin").read_bytes() == refs
    assert not Path(observed.with_suffix(".path").read_text().strip()).exists()
    assert not list(tmp_path.glob("hz-push-refs.*"))
    assert os.access(hook, os.X_OK)
    if refs:
        assert observed.with_suffix(".scan").read_bytes() == refs
        assert observed.with_suffix(".remote").read_text().strip() == "unused"
    else:
        assert not observed.with_suffix(".scan").exists()


def test_scanner_failure_stops_before_prek_and_cleans_preserved_input(tmp_path):
    scanner = tmp_path / "uv"
    scanner.write_text('#!/bin/sh\nprintf \'%s\\n\' "$HZ_DEV_PUSH_REFS_FILE" > "$OBSERVED"\nexit 9\n')
    scanner.chmod(0o755)
    hook = tmp_path / "pre-push"
    hook.write_text(
        '#!/bin/sh\n# File generated by prek: https://prek.j178.dev\nPREK="must-not-execute"\n'
        'exec "$PREK" hook-impl --hook-type=pre-push -- "$@"\n'
    )
    hook.chmod(0o755)
    hooks.preserve_refs(hook)
    observed = tmp_path / "observed"
    done = subprocess.run(
        [str(hook), "origin", "unused"],
        input=b"pushed refs",
        env=os.environ
        | {"OBSERVED": str(observed), "TMPDIR": str(tmp_path), "PATH": f"{tmp_path}{os.pathsep}{os.environ['PATH']}"},
        capture_output=True,
        check=False,
        timeout=5,
    )
    assert done.returncode == 9, done.stderr
    assert not Path(observed.read_text().strip()).exists()
    assert not list(tmp_path.glob("hz-push-refs.*"))


def test_unfamiliar_hook_is_not_overwritten(tmp_path):
    hook = tmp_path / "pre-push"
    original = "#!/bin/sh\nexit 1\n"
    hook.write_text(original)
    with pytest.raises(ValueError, match="expected prek shim"):
        hooks.preserve_refs(hook)
    assert hook.read_text() == original


def test_a_marker_does_not_make_an_unfamiliar_hook_trusted(tmp_path):
    hook = tmp_path / "pre-push"
    original = f"#!/bin/sh\n{hooks.MARKER}\nexit 0\n"
    hook.write_text(original)
    with pytest.raises(ValueError, match="expected prek shim"):
        hooks.preserve_refs(hook)
    assert hook.read_text() == original
