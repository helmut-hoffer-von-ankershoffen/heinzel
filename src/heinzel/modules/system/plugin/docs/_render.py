"""Render a plugin's page as GitHub-flavoured Markdown, and a theme's swatches as SVG (ADR 0058).

The page is written for people first: what the plugin is, how to install it and what it looks like, then the
reference an agent or an integrator needs. Everything comes from the `PluginPage` model; nothing is read here.
"""

import json
from collections.abc import Iterable
from html import escape

from rich.console import Group, RenderableType
from rich.table import Table
from rich.text import Text

from heinzel.modules.system.plugin.docs._models import (
    Documentation,
    ModuleDoc,
    OperationDoc,
    PluginPage,
    Recording,
    Scene,
    SceneStep,
    ThemeDoc,
)

KIND_WORDS = {
    "connector": "Connector: brings adapters for capabilities such as the tracker or the calendar (ADR 0028)",
    "theme": "Theme: offers a look for the web app (ADR 0044)",
    "capability": "Capability: adds operations of its own, commands people and agents run",
    "playbook": "Playbook: brings asset types and contract templates for a kind of team work (ADR 0037)",
    "layer": "Layer: sits in a company's tree and shapes what the people in it get (ADR 0040)",
}
GENERATED = (
    "<!-- Generated by `hz system plugin docs build` from the installed plugin; edit the code, not this page. -->"
)
SWATCH = 28
"""The side of one colour square in a swatch, in pixels."""
SWATCH_TOKENS = ("background", "foreground", "primary", "accent", "card", "border", "ok", "warn", "bad")
"""The tokens a swatch shows, the ones that give a theme its character; the page's table lists them all."""


def page(doc: PluginPage) -> str:
    """The Markdown page of a plugin."""
    lines = [GENERATED, "", f"# {doc.distribution}", ""]
    lines += [doc.summary, ""]
    lines += _facts(doc)
    lines += _recordings(doc.scenes, doc.recordings)
    if doc.themes:
        lines += ["## Themes", ""]
        for theme in doc.themes:
            lines += _theme(theme)
    lines += _operations(doc)
    lines += _settings(doc.modules)
    lines += _credentials(doc.modules)
    lines += _adapters(doc)
    lines += _playbooks(doc)
    lines += _jobs(doc)
    lines += _layers(doc)
    lines += _setup_and_health(doc.modules)
    if doc.other_lets:
        lines += ["## Also declares", ""]
        lines += [
            f"- `{let.kind}` `{let.name}` in `{let.module}`" + (f": {let.summary}" if let.summary else "")
            for let in doc.other_lets
        ]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _facts(doc: PluginPage) -> list[str]:
    kinds = ", ".join(f"**{kind}**" for kind in doc.kinds) or "—"
    where = (
        "built into Heinzelmännchen"
        if doc.builtin
        else ("first-party, released with Heinzelmännchen" if doc.first_party else "community or company plugin")
    )
    lines = ["| | |", "| --- | --- |", f"| Kind | {kinds} |", f"| Version | `{doc.version}` ({where}) |"]
    if doc.repository:
        lines.append(f"| Source | <{doc.repository}> |")
    if doc.license:
        lines.append(f"| Licence | {doc.license} |")
    lines.append(f"| Install | `{doc.install}` |")
    lines.append(f"| Modules | {', '.join(f'`{m.qualname}`' for m in doc.modules) or '—'} |")
    if not doc.enabled:
        lines.append("| Enabled | no: `hz system plugin enable " + doc.distribution + "` |")
    lines.append("")
    explained = [KIND_WORDS[kind] for kind in doc.kinds if kind in KIND_WORDS]
    if explained:
        lines += [f"- {text}." for text in explained]
        lines.append("")
    return lines


def _recordings(scenes: list[Scene], recordings: list[Recording]) -> list[str]:
    if not scenes:
        return []
    lines = ["## See it", ""]
    found = {r.scene: r for r in recordings}
    for scene in scenes:
        recording = found.get(scene.name)
        lines += [f"### {scene.title}", ""]
        if recording and recording.animation:
            alt = escape(f"{scene.title}: " + _alt(scene), quote=True)
            if recording.still:
                lines += [
                    "<picture>",
                    f'  <source srcset="{recording.still}" media="(prefers-reduced-motion: reduce)" />',
                    f'  <img src="{recording.animation}" alt="{alt}" width="100%" />',
                    "</picture>",
                    "",
                ]
            else:
                lines += [f'<img src="{recording.animation}" alt="{alt}" width="100%" />', ""]
            if recording.video:
                lines += [
                    f"[Video]({recording.video})" + (f" · [Still]({recording.still})" if recording.still else ""),
                    "",
                ]
        else:
            lines += [
                "*Not recorded yet: `make docs-record` renders this scene*"
                + (" (derived from the operations; a `docs/scenes.toml` replaces it)." if scene.derived else "."),
                "",
            ]
        lines += ["<details>", "<summary>What it shows</summary>", ""]
        if recording and recording.transcript:
            lines += [recording.transcript, ""]
        elif scene.kind == "cli":
            lines += ["```bash", *scene.commands, "```", ""]
        else:
            lines += [f"{i}. {_step_text(step)}" for i, step in enumerate(scene.steps, 1)] + [""]
        lines += ["</details>", ""]
    return lines


def _alt(scene: Scene) -> str:
    if scene.kind == "cli":
        return "a terminal running " + ", ".join(f"`{c}`" for c in scene.commands)
    captions = [step.caption for step in scene.steps if step.action == "screenshot" and step.caption]
    return "the web app showing " + "; then ".join(captions) if captions else "the web app"


STEP_TEXT = {
    "goto": "Open `{target}`.",
    "click": "Click the {role} “{target}”.",
    "hover": "Hover over the {role} “{target}”.",
    "fill": "Type into “{target}”.",
    "key": "Press {target}.",
    "wait": "Wait for “{target}”.",
}


def _step_text(step: SceneStep) -> str:
    template = STEP_TEXT.get(step.action)
    if template is None:
        return step.caption or "Take a screenshot."
    text = template.format(target=step.target, role=step.role or "element")
    return f"{text} (skipped when it isn't there)" if step.optional else text


def _theme(theme: ThemeDoc) -> list[str]:
    lines = [f"### {theme.title} (`{theme.name}`)", ""]
    lines += [f"Offered by `{theme.module}`; pick it with `{theme.command}`.", ""]
    lines += [
        f'<img src="assets/theme-{theme.name}.svg" alt="Swatches of the {theme.title} theme, light and dark" />',
        "",
    ]
    lines += ["| Token | Light | Dark |", "| --- | --- | --- |"]
    lines += [f"| `{c.token}` | `{c.light or '—'}` | `{c.dark or '—'}` |" for c in theme.colours]
    lines += [
        "",
        f"Fonts: `{theme.font_sans}` and `{theme.font_mono}`"
        + (f", shipping {', '.join(theme.fonts)}" if theme.fonts else "")
        + f". Radius `{theme.radius}`, borders `{theme.border_width}`"
        + (", with its own logo." if theme.logo else "."),
        "",
    ]
    return lines


def _operations(doc: PluginPage) -> list[str]:
    operations = [op for module in doc.modules for op in module.operations]
    if not operations:
        return []
    lines = ["## Operations", ""]
    lines += [
        (
            "An operation is a `hz` command, an MCP tool (`hz system serve mcp`), a REST endpoint "
            "(`hz system serve api`) and an endpoint of the web app's API, unless it restricts its heads. Every "
            "command takes `--json`."
        ),
        "",
        "| Operation | CLI | MCP tool | REST | Web | Changes state | Audience |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for op in operations:
        lines.append(
            f"| {op.summary} | {f'`{op.command}`' if op.command else '—'} | {f'`{op.tool}`' if op.tool else '—'} | "
            f"{f'`{op.endpoint}`' if op.endpoint else '—'} | {f'`{op.web_endpoint}`' if op.web_endpoint else '—'} | "
            f"{'' if op.read_only else 'yes'} | {op.audience} |"
        )
    lines.append("")
    for op in operations:
        lines += _operation(op)
    return lines


def _operation(op: OperationDoc) -> list[str]:
    lines = [f"### `{op.command}`" if op.command else f"### `{op.module}` `{op.name}`", "", op.summary, ""]
    if op.description:
        lines += [op.description, ""]
    if op.usage:
        lines += ["```bash", op.usage, "```", ""]
    if op.parameters:
        lines += ["| Parameter | Type | Default | Description |", "| --- | --- | --- | --- |"]
        for p in op.parameters:
            default = "*required*" if p.required else f"`{json.dumps(p.default)}`"
            lines.append(f"| `{p.name}` | {p.type} | {default} | {p.description} |")
        lines.append("")
    if op.requires:
        lines += ["Needs: " + ", ".join(f"`{r}`" for r in op.requires) + ".", ""]
    if op.heads:
        lines += ["Heads: " + ", ".join(f"`{h}`" for h in op.heads) + " only.", ""]
    if op.tool:
        lines += [
            "<details>",
            f"<summary>MCP tool <code>{op.tool}</code>: input schema</summary>",
            "",
            "```json",
            json.dumps(op.input_schema, indent=2, ensure_ascii=False),
            "```",
            "",
            "</details>",
            "",
        ]
    return lines


def _settings(modules: Iterable[ModuleDoc]) -> list[str]:
    lines: list[str] = []
    for module in modules:
        if not module.settings:
            continue
        if not lines:
            lines += [
                "## Settings",
                "",
                "In your configuration file (`hz system config set <key> <value>`), or as environment variables.",
                "",
            ]
        lines += [
            f"### `[{module.qualname}]`",
            "",
            "| Key | Type | Default | Environment variable | Description |",
            "| --- | --- | --- | --- | --- |",
        ]
        for s in module.settings:
            note = " (user scope only)" if s.ignored_in_project else ""
            lines.append(f"| `{s.key}` | {s.type} | `{s.default}` | `{s.environment}` | {s.description}{note} |")
        lines.append("")
    return lines


def _credentials(modules: Iterable[ModuleDoc]) -> list[str]:
    rows = [c for module in modules for c in module.credentials]
    if not rows:
        return []
    lines = [
        "## Credentials",
        "",
        "Kept in the OS keychain (ADR 0030); names only, never values.",
        "",
        "| Credential | Purpose | Store it |",
        "| --- | --- | --- |",
    ]
    lines += [f"| `{c.name}` | {c.purpose} | `{c.command}` |" for c in rows]
    return [*lines, ""]


def _adapters(doc: PluginPage) -> list[str]:
    if not doc.adapters:
        return []
    lines = [
        "## Capabilities served",
        "",
        "| Adapter | Capability | Modes | Sends data to | Bind it |",
        "| --- | --- | --- | --- | --- |",
    ]
    for a in doc.adapters:
        hosts = ", ".join(f"`{h}`" for h in a.hosts) or ("its settings decide" if a.hosts_from_settings else "—")
        lines.append(f"| `{a.adapter}` | `{a.capability}` | {', '.join(a.modes)} | {hosts} | `{a.binding}` |")
    requires = sorted({r for module in doc.modules for r in module.requires})
    lines.append("")
    if requires:
        lines += ["Reads: " + ", ".join(f"`{r}`" for r in requires) + ".", ""]
    return lines


def _playbooks(doc: PluginPage) -> list[str]:
    if not doc.playbooks:
        return []
    lines = ["## Playbooks", ""]
    for p in doc.playbooks:
        lines += [f"### `{p.module}`", "", p.summary, ""]
        if p.assets:
            lines += ["| Asset type | What it is | Where to look | Kept by |", "| --- | --- | --- | --- |"]
            for a in p.assets:
                kept = f"`{a.kept_by}`" if a.kept_by else "—"
                lines.append(f"| `{a.name}` | {a.description} | {'; '.join(a.hints) or '—'} | {kept} |")
            lines.append("")
        if p.templates:
            lines += [
                "Templates: " + ", ".join(f"`{t}`" for t in p.templates) + " (`hz workflow new --template <name>`).",
                "",
            ]
        if p.defaults:
            lines += ["Recommends: " + ", ".join(f"`{k} = {json.dumps(v)}`" for k, v in p.defaults.items()) + ".", ""]
    return lines


def _jobs(doc: PluginPage) -> list[str]:
    if not doc.jobs:
        return []
    lines = [
        "## Jobs",
        "",
        "Run by `hz system daemon` on a schedule (ADR 0020).",
        "",
        "| Job | What it does | Schedule | Missed slots | Timeout | Reads |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for j in doc.jobs:
        reads = ", ".join(f"`{r}`" for r in j.requires) or "—"
        lines.append(f"| `{j.name}` | {j.summary} | `{j.schedule}` | {j.catch_up} | {j.timeout} | {reads} |")
    return [*lines, ""]


def _layers(doc: PluginPage) -> list[str]:
    if not doc.layers:
        return []
    lines = ["## Layers", "", "| Layer | Parent | Site | Roles |", "| --- | --- | --- | --- |"]
    for layer in doc.layers:
        parent = f"`{layer.parent}`" if layer.parent else "the company"
        site = f"`{layer.site}`" if layer.site else "—"
        lines.append(f"| `{layer.module}` | {parent} | {site} | {', '.join(layer.roles) or '—'} |")
    return [*lines, ""]


def _setup_and_health(modules: Iterable[ModuleDoc]) -> list[str]:
    lines: list[str] = []
    for module in modules:
        if module.setup:
            kind = "required" if module.setup.required else "optional"
            lines.append(
                f"- Setup: `{module.setup.command}` ({kind}, phase {module.setup.phase}), also part of `hz setup`: "
                f"{module.setup.summary}"
            )
        if module.health_checks:
            lines.append(f"- Health: `{module.qualname}` reports to `hz system doctor`.")
        if module.info:
            lines.append(f"- Info: `{module.qualname}` adds a section to `hz system info`.")
    return ["## Setup and health", "", *lines, ""] if lines else []


def swatches(theme: ThemeDoc) -> str:
    """An SVG of the theme's characteristic colours: one row per mode, light above dark."""
    tokens = [c for c in theme.colours if c.token in SWATCH_TOKENS]
    width = len(tokens) * SWATCH
    height = SWATCH * 2
    label = escape(f"{theme.title}: colours in light and dark mode", quote=True)
    box = f'width="{width}" height="{height}" viewBox="0 0 {width} {height}"'
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" {box} role="img" aria-label="{label}">']
    parts.append(f"<title>{escape(theme.title)}</title>")
    for row, mode in enumerate(("light", "dark")):
        for column, colour in enumerate(tokens):
            value = getattr(colour, mode) or "#808080"
            at = f'x="{column * SWATCH}" y="{row * SWATCH}" width="{SWATCH}" height="{SWATCH}"'
            title = f"<title>{escape(colour.token)} ({mode}): {escape(value)}</title>"
            parts.append(f'<rect {at} fill="{escape(value, quote=True)}">{title}</rect>')
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def gallery(pages: list[PluginPage], *, title: str = "Plugins") -> str:
    """An index page: every plugin with its kinds and summary, linked to its page."""
    lines = [GENERATED, "", f"# {title}", "", "| Plugin | Kind | What it does |", "| --- | --- | --- |"]
    for doc in pages:
        kinds = ", ".join(doc.kinds) or "—"
        lines.append(f"| [`{doc.distribution}`]({doc.distribution}/index.md) | {kinds} | {doc.summary} |")
    return "\n".join(lines) + "\n"


def render_documentation(documentation: Documentation) -> RenderableType:
    """The model on a terminal: one table of plugins, then each plugin's operations."""
    table = Table(title="Plugins documented", show_lines=False)
    for column in ("Plugin", "Version", "Kind", "Operations", "Settings", "Themes", "Scenes"):
        table.add_column(column)
    for doc in documentation.pages:
        table.add_row(
            doc.distribution,
            doc.version,
            ", ".join(doc.kinds) or "—",
            str(sum(len(m.operations) for m in doc.modules)),
            str(sum(len(m.settings) for m in doc.modules)),
            ", ".join(t.name for t in doc.themes) or "—",
            ", ".join(s.name for s in doc.scenes) or "—",
        )
    parts: list[RenderableType] = [table]
    parts += [
        Text(f"  {op.command}: {op.summary}")
        for doc in documentation.pages
        for module in doc.modules
        for op in module.operations
    ]
    parts += [Text(f"! {warning}", style="yellow") for warning in documentation.warnings]
    return Group(*parts)
