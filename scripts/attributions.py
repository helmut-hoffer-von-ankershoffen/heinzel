# /// script
# requires-python = ">=3.12"
# dependencies = ["packaging==26.3"]
# ///
"""Generate ATTRIBUTIONS.md: every open-source package hz ships to its users, with its license text. Thank you!

Two parts, each sorted by name:

- Python packages: the runtime dependencies of the core and of every first-party plugin, as uv.lock pins them
  (`uv export --no-dev`), for the platforms hz runs on (macOS and Linux, every supported Python).
  Dev tools are not distributed, so they are not listed. Their metadata and license files come from the very wheels
  uv.lock pins, installed per platform into a throwaway directory (`uv pip install --target --python-platform`), so
  the file is the same whichever machine generates it.
- Web app (JavaScript) packages: the production dependencies of web/ (`pnpm licenses list --prod`), which the wheel
  ships bundled into the web head's app.

The output has no timestamps and a stable order, so a diff shows exactly which packages changed. `--check` compares
the packages listed with what the lockfiles pin now, offline, and fails if they differ: `make fix` regenerates it.

Usage: uv run --script scripts/attributions.py [--check]
"""

import json
import re
import subprocess
import sys
import tempfile
from collections.abc import Iterable
from dataclasses import dataclass
from importlib.metadata import Distribution, distributions
from pathlib import Path

from packaging.markers import Marker
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "ATTRIBUTIONS.md"
PYTHON_SECTION = "Python packages"
WEB_SECTION = "Web app (JavaScript) packages"
PYTHONS = ("3.12", "3.13", "3.14", "3.15")
"""The Pythons hz supports (pyproject's classifiers); a dependency needed on any of them is listed."""
PLATFORMS = {
    "aarch64-apple-darwin": {"sys_platform": "darwin", "platform_system": "Darwin", "platform_machine": "arm64"},
    "x86_64-manylinux_2_28": {"sys_platform": "linux", "platform_system": "Linux", "platform_machine": "x86_64"},
}
"""The platforms hz runs on, as `uv pip install --python-platform` names them, with their marker values."""
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|COPYRIGHT)([._-].*)?$", re.IGNORECASE)
CLASSIFIER_SPDX = {
    "Apache Software License": "Apache-2.0",
    "BSD License": "BSD",
    "GNU Lesser General Public License v3 (LGPLv3)": "LGPL-3.0",
    "ISC License (ISCL)": "ISC",
    "MIT License": "MIT",
    "Mozilla Public License 2.0 (MPL 2.0)": "MPL-2.0",
    "Python Software Foundation License": "PSF-2.0",
}
"""Trove license classifiers by SPDX identifier, for packages that predate the License-Expression field."""
SOURCE_URLS = ("source", "source code", "repository", "code", "github", "homepage", "home", "documentation")
TIMEOUT = 600

INTRO = """\
# Attributions

<!-- Generated by `make attributions` (part of `make fix`) from uv.lock and web/pnpm-lock.yaml; don't edit. -->

Heinzelmännchen stands on the shoulders of giants. Every package below is open source, written and maintained by
people who chose to share their work with all of us, and `hz` would not exist without them. **Thank you.**

This is every package `hz` ships to its users, with its license and the license text it comes with:
{python} Python packages that install with `hz` and its first-party plugins on macOS and Linux, and {web}
JavaScript packages bundled into its web app. Tools that only build or test `hz` are not distributed, so they are not
listed, though we are just as grateful for them. Licenses are checked against
[.license-allowlist](.license-allowlist) by `make audit`.
"""


@dataclass(frozen=True)
class Package:
    """One package as ATTRIBUTIONS.md lists it."""

    name: str
    version: str
    license: str
    url: str
    texts: tuple[tuple[str, str], ...]
    """The license files it ships, as (file name, text)."""

    @property
    def title(self) -> str:
        """Its heading, which --check reads back."""
        return f"{self.name} {self.version}"


def run(*command: str) -> str:
    """Run a command in the repository and return what it printed.

    Raises:
        SystemExit: The command failed; its error output says why.
    """
    done = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, check=False, timeout=TIMEOUT)  # noqa: S603
    if done.returncode != 0:
        msg = f"{' '.join(command[:4])} ... failed:\n{done.stderr.strip()[-2000:]}"
        raise SystemExit(msg)
    return done.stdout


def environments() -> list[tuple[str, dict[str, str]]]:
    """Every (platform, marker environment) hz runs in: each platform with each supported Python."""
    return [
        (
            platform,
            {
                **values,
                "os_name": "posix",
                "implementation_name": "cpython",
                "platform_python_implementation": "CPython",
                "python_version": python,
                "python_full_version": f"{python}.0",
            },
        )
        for platform, values in PLATFORMS.items()
        for python in PYTHONS
    ]


def locked_requirements(exported: str) -> dict[str, list[Requirement]]:
    """The pinned requirements of `uv export`, by the platforms that need them."""
    needed: dict[str, list[Requirement]] = {platform: [] for platform in PLATFORMS}
    for line in exported.splitlines():
        line = line.strip()  # noqa: PLW2901
        if not line or line.startswith(("#", "-")):
            continue
        requirement = Requirement(line)
        marker = requirement.marker or Marker("python_version >= '3'")
        for platform in {platform for platform, env in environments() if marker.evaluate(env)}:
            if requirement not in needed[platform]:
                needed[platform].append(requirement)
    return needed


def export() -> str:
    """uv.lock's runtime dependencies of the core and every first-party plugin, as pinned requirements."""
    return run(
        "uv", "export", "--quiet", "--frozen", "--no-dev", "--all-packages", "--no-emit-workspace",
        "--no-hashes", "--no-annotate", "--no-header", "--format", "requirements-txt",
    )  # fmt: skip


def python_titles(exported: str) -> set[str]:
    """The headings the Python section must have: one per pinned runtime dependency."""
    return {
        f"{canonicalize_name(r.name)} {r.specifier}".replace("==", "")
        for requirements in locked_requirements(exported).values()
        for r in requirements
    }


def spdx(metadata: dict[str, list[str]]) -> str:
    """A distribution's license: its License-Expression, a short License field, or its trove classifiers."""
    if expression := metadata.get("license-expression"):
        return expression[0].strip()
    classifiers = [
        CLASSIFIER_SPDX.get(c.rsplit(" :: ", 1)[-1], c.rsplit(" :: ", 1)[-1])
        for c in metadata.get("classifier", [])
        if c.startswith("License :: ") and c != "License :: OSI Approved"
    ]
    if classifiers:
        return " OR ".join(sorted(set(classifiers)))
    short = [value.strip() for value in metadata.get("license", []) if value.strip() and "\n" not in value.strip()]
    return short[0] if short and len(short[0]) <= 60 else "see the license text"  # noqa: PLR2004


def python_url(name: str, metadata: dict[str, list[str]]) -> str:
    """Where a distribution's source lives: a source or home Project-URL, its Home-page, or its page on PyPI."""
    urls: dict[str, str] = {}
    for entry in metadata.get("project-url", []):
        label, _, url = entry.partition(",")
        urls.setdefault(label.strip().lower().replace("-", " ").replace("_", " "), url.strip())
    for label in SOURCE_URLS:
        if label in urls:
            return urls[label]
    if home := metadata.get("home-page"):
        return home[0].strip()
    return f"https://pypi.org/project/{name}/"


def python_texts(dist: Distribution) -> tuple[tuple[str, str], ...]:
    """The license files a distribution ships in its .dist-info (PEP 639's licenses/ folder, or the older layout)."""
    files = [
        file
        for file in dist.files or []
        if ".dist-info" in file.parts[0] and LICENSE_FILE.match(file.name) and file.suffix not in {".py", ".pyc"}
    ]
    found = {"/".join(f.parts[1:]).removeprefix("licenses/"): f.read_text(encoding="utf-8") for f in files}
    return tuple(sorted(found.items()))


def python_package(dist: Distribution) -> Package:
    """A Python distribution as ATTRIBUTIONS.md lists it."""
    metadata: dict[str, list[str]] = {}
    for key in dict.fromkeys(dist.metadata):
        metadata[key.lower()] = [str(value) for value in dist.metadata.get_all(key) or []]
    name = canonicalize_name(dist.metadata["Name"])
    return Package(name, dist.version, spdx(metadata), python_url(name, metadata), python_texts(dist))


def python_packages(exported: str) -> list[Package]:
    """Every runtime Python dependency, read from the wheels uv.lock pins, installed per platform."""
    packages: dict[str, Package] = {}
    with tempfile.TemporaryDirectory(prefix="hz-attributions-") as temporary:
        for platform, requirements in locked_requirements(exported).items():
            target = Path(temporary) / platform
            listing = target.with_suffix(".txt")
            listing.write_text("\n".join(str(r).split(";")[0].strip() for r in requirements) + "\n", "utf-8")
            run(
                "uv", "pip", "install", "--quiet", "--no-deps", "--no-config", "--target", str(target),
                "--python-platform", platform, "--python-version", PYTHONS[0], "-r", str(listing),
            )  # fmt: skip
            for dist in distributions(path=[str(target)]):
                package = python_package(dist)
                packages.setdefault(package.name, package)
    return sorted(packages.values(), key=lambda p: p.name)


def web_listing() -> dict[str, list[dict[str, object]]]:
    """`pnpm licenses list --prod --json` of web/, through scripts/web_build.py (which installs web/ if stale)."""
    listing: dict[str, list[dict[str, object]]] = json.loads(
        run("uv", "run", "--quiet", "--script", "scripts/web_build.py", "licenses", "--json")
    )
    return listing


def repository_url(manifest: dict[str, object]) -> str | None:
    """A package.json's repository as a browsable URL (git+https://...git, github:owner/repo and owner/repo)."""
    repository = manifest.get("repository")
    url = repository.get("url") if isinstance(repository, dict) else repository
    if not isinstance(url, str) or not url:
        return None
    url = re.sub(r"^git\+", "", url).removesuffix(".git").replace("git://", "https://")
    url = re.sub(r"^git@github\.com:", "https://github.com/", url)
    url = re.sub(r"^ssh://git@", "https://", url)
    if url.startswith("github:"):
        url = "https://github.com/" + url.removeprefix("github:")
    elif re.fullmatch(r"[\w.-]+/[\w.-]+", url):
        url = f"https://github.com/{url}"
    return url


def web_packages(listing: dict[str, list[dict[str, object]]]) -> list[Package]:
    """Every production dependency of web/, one entry per installed version, with the license files it ships."""
    packages: list[Package] = []
    for license_, entries in listing.items():
        for entry in entries:
            name = str(entry["name"])
            for version, path in zip(entry["versions"], entry["paths"], strict=True):  # type: ignore[call-overload]
                folder = Path(path)
                manifest = json.loads((folder / "package.json").read_text(encoding="utf-8"))
                homepage = entry.get("homepage") or manifest.get("homepage")
                url = str(homepage or repository_url(manifest) or f"https://www.npmjs.com/package/{name}")
                texts = tuple(
                    (file.name, file.read_text(encoding="utf-8", errors="replace"))
                    for file in sorted(folder.iterdir(), key=lambda f: f.name)
                    if file.is_file() and LICENSE_FILE.match(file.name)
                )
                packages.append(Package(name, str(version), license_, url, texts))
    return sorted(packages, key=lambda p: (p.name.lstrip("@").lower(), p.name, p.version))


def web_titles(listing: dict[str, list[dict[str, object]]]) -> set[str]:
    """The headings the web section must have: one per production dependency and version."""
    return {
        f"{entry['name']} {version}"
        for entries in listing.values()
        for entry in entries
        for version in entry["versions"]  # type: ignore[attr-defined]
    }


def anchor(title: str, seen: dict[str, int]) -> str:
    """The anchor GitHub gives a heading: lowercase, punctuation dropped, spaces to hyphens, repeats numbered."""
    slug = re.sub(r"[^\w\- ]", "", title.lower()).replace(" ", "-")
    count = seen.get(slug, 0)
    seen[slug] = count + 1
    return f"{slug}-{count}" if count else slug


def clean(text: str) -> str:
    """A license text as the file shows it: Unix line ends, no trailing spaces, no blank lines around it."""
    lines = text.replace("\r\n", "\n").replace("\r", "\n").expandtabs(4).split("\n")
    return "\n".join(line.rstrip() for line in lines).strip("\n")


def fence(text: str) -> str:
    """A code fence longer than any run of backticks in `text`, so a license text can't end the block."""
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    return "`" * max(3, longest + 1)


def section(heading: str, about: str, packages: Iterable[Package], seen: dict[str, int]) -> list[str]:
    """One part of ATTRIBUTIONS.md: a table of every package, then each one with its license text."""
    packages = list(packages)
    anchors = [anchor(p.title, seen) for p in packages]
    lines = [f"## {heading}", "", about, "", "| Package | Version | License |", "| --- | --- | --- |"]
    lines += [f"| [{p.name}](#{a}) | {p.version} | {p.license.replace('|', '/')} |" for p, a in zip(packages, anchors)]  # noqa: B905
    for package in packages:
        lines += ["", f"### {package.title}", "", f"- License: {package.license}", f"- Homepage: <{package.url}>", ""]
        if not package.texts:
            lines += ["No license file ships with this package; its metadata declares the license above."]
            continue
        lines += ["<details>", "<summary>License text</summary>", ""]
        for index, (file, text) in enumerate(package.texts):
            body = clean(text)
            mark = fence(body)
            if len(package.texts) > 1:
                lines += ([""] if index else []) + [f"`{file}`:", ""]
            lines += [f"{mark}text", body, mark]
        lines += ["", "</details>"]
    return lines


def render(python: list[Package], web: list[Package]) -> str:
    """ATTRIBUTIONS.md."""
    seen: dict[str, int] = {}
    lines = [INTRO.format(python=len(python), web=len(web)).rstrip(), ""]
    lines += section(
        PYTHON_SECTION,
        "Installed with `hz`: the runtime dependencies of the core and of every first-party plugin.",
        python,
        seen,
    )
    lines += [""]
    lines += section(
        WEB_SECTION,
        "Bundled into the web app that `hz ui` serves: the production dependencies of [web/](web/package.json).",
        web,
        seen,
    )
    return "\n".join(lines) + "\n"


def listed(text: str) -> dict[str, set[str]]:
    """The package headings of each part of an ATTRIBUTIONS.md; headings inside a license text don't count."""
    found: dict[str, set[str]] = {PYTHON_SECTION: set(), WEB_SECTION: set()}
    current: set[str] | None = None
    open_fence = ""
    for line in text.splitlines():
        if open_fence:
            open_fence = "" if line == open_fence else open_fence
        elif fenced := re.match(r"^`{3,}", line):
            open_fence = fenced.group()
        elif line.startswith("## "):
            current = found.get(line.removeprefix("## "))
        elif line.startswith("### ") and current is not None:
            current.add(line.removeprefix("### "))
    return found


def differences(text: str, expected: dict[str, set[str]]) -> list[str]:
    """What an ATTRIBUTIONS.md lists that the lockfiles don't pin, and what it misses."""
    found = listed(text)
    problems: list[str] = []
    for part, titles in expected.items():
        problems += [f"{part}: missing {title}" for title in sorted(titles - found[part])]
        problems += [f"{part}: no longer shipped {title}" for title in sorted(found[part] - titles)]
    return problems


def main(argv: list[str]) -> int:
    """Write ATTRIBUTIONS.md, or with --check compare the packages it lists with the lockfiles."""
    exported, listing = export(), web_listing()
    if "--check" in argv:
        text = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        problems = differences(text, {PYTHON_SECTION: python_titles(exported), WEB_SECTION: web_titles(listing)})
        if problems:
            print("ATTRIBUTIONS.md is out of date; run `make fix`:", *problems, sep="\n  ", file=sys.stderr)
            return 1
        return 0
    content = render(python_packages(exported), web_packages(listing))
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
        OUTPUT.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
