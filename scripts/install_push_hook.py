"""Preserve Git's complete pushed-ref list before prek consumes the hook's standard input.

Run after `prek install`. The confidentiality scanner needs every pushed ref, while prek exposes only its first
range to configured hooks. Replaying the captured input keeps prek's existing hook execution unchanged.
"""

import os
import subprocess
from pathlib import Path

RUNNER = 'exec "$PREK" hook-impl '
INVOCATION = '--hook-type=pre-push -- "$@"'
REPLAY = f'{INVOCATION} < "$HZ_DEV_PUSH_REFS_FILE"'
MARKER = "# Preserve Git's complete ref list for the confidentiality push check."
CAPTURE = (
    f"{MARKER}\n"
    'HZ_DEV_PUSH_REFS_FILE="$(mktemp "${TMPDIR:-/tmp}/hz-push-refs.XXXXXX")" || exit 1\n'
    "trap 'rm -f -- \"$HZ_DEV_PUSH_REFS_FILE\"' EXIT\n"
    "trap 'exit 1' HUP INT TERM\n"
    'cat > "$HZ_DEV_PUSH_REFS_FILE" || exit 1\n'
    "export HZ_DEV_PUSH_REFS_FILE\n"
    'if [ -s "$HZ_DEV_PUSH_REFS_FILE" ]; then\n'
    '    PRE_COMMIT_REMOTE_URL="$2" uv run --quiet --script scripts/check_confidentiality.py --push '
    '< "$HZ_DEV_PUSH_REFS_FILE" || exit $?\n'
    "fi\n"
    '"$PREK" hook-impl '
)


def preserve_refs(path: Path) -> None:
    """Wrap a generated prek pre-push hook, refusing unfamiliar hook code.

    Raises:
        ValueError: If the hook is not the generated prek shim expected here.
    """
    source = path.read_text(encoding="utf-8")
    generated = "# File generated by prek:" in source
    if generated and source.count(CAPTURE) == 1 and source.count(REPLAY) == 1 and RUNNER not in source:
        return
    if not generated or MARKER in source or source.count(RUNNER) != 1 or source.count(INVOCATION) != 1:
        msg = "The pre-push hook is not the expected prek shim; run make setup with the pinned prek version"
        raise ValueError(msg)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    try:
        wrapped = source.replace(RUNNER, CAPTURE)
        wrapped = wrapped.replace(INVOCATION, REPLAY)
        temporary.write_text(wrapped, encoding="utf-8")
        temporary.chmod(path.stat().st_mode)
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def main() -> None:
    """Find Git's effective pre-push hook and preserve its complete ref list."""
    hook = subprocess.check_output(
        ["git", "rev-parse", "--git-path", "hooks/pre-push"],  # noqa: S607 - repository Git from PATH
        text=True,
        timeout=30,
    ).strip()
    preserve_refs(Path(hook))


if __name__ == "__main__":
    main()
