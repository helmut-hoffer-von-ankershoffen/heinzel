// Seal reviewed standard-library helpers; the runtime never reads helper source from an arbitrary checkout.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = ["// Generated by tools/runtime-code.mjs from the reviewed runtime/*.py helpers."];
for (const name of ["broker", "worker"])
  source.push(
    `export const ${name.toUpperCase()}_CODE = ${JSON.stringify(readFileSync(new URL(`../runtime/${name}.py`, import.meta.url), "utf8"))};`,
  );
const formatted = execFileSync(
  process.execPath,
  [
    fileURLToPath(new URL("../node_modules/@biomejs/biome/bin/biome", import.meta.url)),
    "format",
    "--stdin-file-path=src/runtime-code.ts",
  ],
  { cwd: fileURLToPath(new URL("..", import.meta.url)), input: `${source.join("\n")}\n`, encoding: "utf8" },
);
const destination = fileURLToPath(new URL("../src/runtime-code.ts", import.meta.url));
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== formatted) throw new Error("Rebuild the sealed managed runtime helpers.");
} else writeFileSync(destination, formatted);
